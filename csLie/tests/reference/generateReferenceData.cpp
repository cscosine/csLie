// Generates ReferenceData.hpp (to stdout): inputs of the csLie accuracy tests and their exact results, computed in
// quad precision (QuadReference.hpp). Built where __float128 and libquadmath exist (GCC on x86-64 Linux), not
// installed. The test "csLie reference data up to date" fails when its output differs from the committed
// ReferenceData.hpp; to regenerate it after changing this file or QuadReference.hpp:
//   cmake --build <build dir> --config <config> --target csLieRegenerateReferenceData
// Each input is rounded to the tested precision first; its reference is computed from that rounded value, so a
// test measures the error of the function alone. Values are written as hexadecimal floating literals (exact).
#include "QuadReference.hpp"

#include <cstdio>
#include <string>
#include <vector>

namespace {

using ref::Q;

struct Angle {
  char const *label;
  Q theta;
};

std::vector<Angle> const &angles() {
  static std::vector<Angle> const a{
      {"0", 0},
      {"1e-12", Q(1e-12)},
      {"1e-10", Q(1e-10)},
      {"1e-8", Q(1e-8)},
      {"1e-6", Q(1e-6)},
      {"1e-4", Q(1e-4)},
      {"1e-3", Q(1e-3)},
      {"1deg", ref::PI / 180},
      {"0.1", Q(0.1)},
      {"0.5", Q(0.5)},
      {"1", Q(1)},
      {"2", Q(2)},
      {"2pi/3", 2 * ref::PI / 3},
      {"3", Q(3)},
      {"pi-1e-2", ref::PI - Q(1e-2)},
      {"pi-1e-4", ref::PI - Q(1e-4)},
      {"pi-1e-6", ref::PI - Q(1e-6)},
      {"pi-1e-8", ref::PI - Q(1e-8)},
  };
  return a;
}

struct Axis {
  char const *label;
  ref::V3 v;
};

std::vector<Axis> const &axes() {
  static std::vector<Axis> const a = [] {
    std::vector<Axis> o;
    auto add = [&](char const *label, Q x, Q y, Q z) {
      ref::V3 v;
      v(0, 0) = x, v(1, 0) = y, v(2, 0) = z;
      Q const n = ref::norm(v);
      for (auto &e : v.a)
        e /= n;
      o.push_back({label, v});
    };
    add("x", 1, 0, 0);
    add("y", 0, 1, 0);
    add("z", 0, 0, 1);
    add("-z", 0, 0, -1);
    add("xyz", 1, 1, 1);
    add("x-y", 1, -1, 0);
    add("r1", Q(0.3), Q(-0.8), Q(0.52));
    add("r2", Q(-0.91), Q(0.12), Q(-0.4));
    add("r3", Q(0.05), Q(0.6), Q(-0.79));
    return o;
  }();
  return a;
}

// rotations by exactly pi, exactly representable
std::vector<std::pair<char const *, std::array<int, 9>>> const &exactPi() {
  static std::vector<std::pair<char const *, std::array<int, 9>>> const m{
      {"pi x", {1, 0, 0, 0, -1, 0, 0, 0, -1}},  {"pi y", {-1, 0, 0, 0, 1, 0, 0, 0, -1}},
      {"pi z", {-1, 0, 0, 0, -1, 0, 0, 0, 1}},  {"pi x+y", {0, 1, 0, 1, 0, 0, 0, 0, -1}},
      {"pi x+z", {0, 0, 1, 0, -1, 0, 1, 0, 0}},
  };
  return m;
}

template <class T> Q roundTo(Q v) { return Q(static_cast<T>(v)); }

std::string hex(Q v) {
  char b[64];
  std::snprintf(b, sizeof b, "%a", static_cast<double>(v));
  return b;
}

template <int R, int C> std::string list(ref::M<R, C> const &m) {
  std::string s;
  for (int i = 0; i < R * C; ++i)
    s += (i ? ", " : "") + hex(m.a[i]);
  return s;
}

template <class T> void so3LogCases(char const *name) {
  std::printf("inline constexpr So3LogCase %s[] = {\n", name);
  auto emit = [](std::string const &label, ref::M3 const &R) {
    std::printf("    {\"%s\", {%s}, {%s}},\n", label.c_str(), list(R).c_str(), list(ref::so3Log(R)).c_str());
  };
  for (auto const &an : angles())
    for (auto const &ax : axes()) {
      ref::V3 w;
      for (int i = 0; i < 3; ++i)
        w(i, 0) = an.theta * ax.v(i, 0);
      ref::M3 R = ref::so3Exp(w);
      for (auto &e : R.a)
        e = roundTo<T>(e);
      emit(std::string(an.label) + " " + ax.label, R);
      if (an.theta == 0)
        break; // one identity is enough
    }
  for (auto const &[label, m] : exactPi()) {
    ref::M3 R;
    for (int i = 0; i < 9; ++i)
      R.a[i] = m[i];
    emit(label, R);
  }
  std::printf("};\n\n");
}

} // namespace

int main() {
  std::printf("// Generated by generateReferenceData.cpp: do not edit, regenerate.\n"
              "// clang-format off\n"
              "#pragma once\n\n"
              "namespace csLie::testReference {\n\n"
              "/// a rotation matrix (row major, exactly representable in the tested precision) and its exact log\n"
              "struct So3LogCase {\n"
              "  char const *label;\n"
              "  double R[9];\n"
              "  double omega[3];\n"
              "};\n\n");
  so3LogCases<float>("so3LogCasesF32");
  so3LogCases<double>("so3LogCasesF64");
  std::printf("} // namespace csLie::testReference\n"
              "// clang-format on\n");
}
